"""Turn a server's snapshot (and optionally its AMI's) into manifest data.

Categories:
  1 hand_placed             unowned paths that are not noise; with a baseline,
                            only those added or changed since it (content, type,
                            mode, owner, link target, extended attributes, SELinux
                            label)
  2 modified_package_files  package files that differ from what was installed
                            (rpm -V / dpkg --verify), flagged since_baseline
  3 packages                installed packages, and changes since the baseline
  4 noise                   how many paths each noise rule hid
What would otherwise crowd 1 is reported in groups of its own: language_packages
(pip, npm), alternatives, package_scripts (made during a dnf / yum / apt run),
cloud_init (made by cloud-init at first boot), snaps and containers. Plus deleted
(hand-placed files gone since the baseline), services (links in /etc/systemd/system),
package_files_to_review and warnings.

サーバーのスナップショット（と、あればその AMI のもの）を manifest データにする。区分は
次のとおり: ① hand_placed（無所属でノイズでないパス。baseline があればそれ以降に
増えた・変わったものだけ）② modified_package_files（インストール時と違うパッケージファイル）③
packages（導入済みと baseline からの変化）④ noise（規則ごとに隠した件数）。① を埋めてしまう
ものは別の組にまとめる: language_packages（pip・npm）、alternatives、package_scripts（dnf / yum
/ apt の実行中にできたもの）、cloud_init（初回起動で cloud-init が作ったもの）、snaps、
containers。加えて deleted・services・package_files_to_review・warnings。
"""

